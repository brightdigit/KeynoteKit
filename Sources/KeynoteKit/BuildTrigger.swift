/// When a build starts.
///
/// `onClick` is the trigger every committed fixture and golden uses; the
/// two automatic triggers are archive-supported but verified only by the
/// #24 human acceptance pass.
public enum BuildTrigger: Sendable {
  /// Start on click (the default).
  case onClick

  /// Start after the previous build finishes.
  case afterPrevious

  /// Start together with the previous build.
  case withPrevious
}
